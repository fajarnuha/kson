package bench

import com.fajarnuha.kson.ktor.KsonConverter
import io.ktor.util.reflect.typeInfo
import io.ktor.utils.io.ByteReadChannel
import kotlinx.coroutines.runBlocking
import probe.KsonProbe
import probe.ksonProbeKson
import java.io.File

/** kson-specific checks that the cross-library matrix cannot express. Writes `results/kson-checks.md`. */
fun main(args: Array<String>) {
    val out = File(args.firstOrNull() ?: "results").apply { mkdirs() }
    val report = buildString {
        appendLine("<!-- Generated by `./gradlew -p docs/benchmarks ksonChecks`; do not edit by hand. -->")
        appendLine()
        appendLine("### Equality of the same data decoded through different roots")
        appendLine()
        appendLine("`Payloads.user` and the only user of `Payloads.page(1)` are the same JSON object.")
        appendLine()
        val alone = bench.kson.UserJson.decode(Payloads.user)
        val inPage = bench.kson.UserPageJson.decode(Payloads.page(1)).users.single()
        val kotlinxAlone = Codecs.kotlinx.decodeFromString(bench.kotlinx.User.serializer(), Payloads.user)
        val kotlinxInPage = Codecs.kotlinx.decodeFromString(bench.kotlinx.UserPage.serializer(), Payloads.page(1)).users.single()
        appendLine("| Check | Result |")
        appendLine("|---|---|")
        appendLine("| kson: `UserJson.decode(user) == UserPageJson.decode(page).users[0]` | `${alone == inPage}` |")
        appendLine("| kson: `.address` of each, compared | `${alone.address == inPage.address}` |")
        appendLine("| kson: runtime classes | `${alone.javaClass.name}` vs `${inPage.javaClass.name}` |")
        appendLine("| kson: same JSON when encoded | `${bench.kson.UserJson.encode(alone) == bench.kson.UserJson.encode(inPage)}` |")
        appendLine("| kotlinx (control): same comparison | `${kotlinxAlone == kotlinxInPage}` |")
        appendLine()

        appendLine("### Ktor `KsonConverter.deserialize` failures")
        appendLine()
        appendLine("Ktor callers catch `JsonConvertException` (a `ContentConvertException`); anything else escapes as an unexpected error.")
        appendLine()
        appendLine("| Body | Exception thrown to the caller |")
        appendLine("|---|---|")
        listOf(
            "Malformed JSON" to """{"id":1,""",
            "Missing required key" to """{"id":1}""",
            "Unknown enum constant" to """{"id":1,"name":"a","score":1,"role":"OWNER","inner":{"value":1}}""",
        ).forEach { (title, body) ->
            val outcome = try {
                runBlocking { KsonConverter().deserialize(Charsets.UTF_8, typeInfo<KsonProbe>(), ByteReadChannel(body)) }
                "none"
            } catch (error: Throwable) {
                "`${error.javaClass.name}`: ${error.message?.take(120)}"
            }
            appendLine("| $title `$body` | $outcome |")
        }
        appendLine()

        appendLine("### Builder with a required property left unset")
        appendLine()
        val builder = runCatching { ksonProbeKson { id = 1 } }.exceptionOrNull()
        appendLine("`ksonProbeKson { id = 1 }` → `${builder?.javaClass?.name}`: ${builder?.message}")
    }
    File(out, "kson-checks.md").writeText(report)
    println(report)
}
