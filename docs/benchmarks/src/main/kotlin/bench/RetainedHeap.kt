package bench

import com.google.gson.JsonParser
import org.openjdk.jol.info.GraphLayout
import org.openjdk.jol.vm.VM
import java.io.File
import com.fajarnuha.kson.Json as KsonJson

/**
 * Walks the object graph that each library returns for a 1,000-user page and reports its retained size.
 * This is the memory the decoded result keeps alive, not what decoding allocates along the way
 * (JMH's `gc.alloc.rate.norm` covers that).
 */
fun main(args: Array<String>) {
    val out = File(args.firstOrNull() ?: "results").apply { mkdirs() }
    val page = Payloads.page(1000)

    val typed = linkedMapOf<String, () -> Any?>(
        "kson" to { bench.kson.UserPageJson.decode(page) },
        "kotlinx.serialization" to { Codecs.kotlinx.decodeFromString(bench.kotlinx.UserPage.serializer(), page) },
        "moshi" to { Codecs.moshiPage.fromJson(page) },
        "gson" to { Codecs.gson.fromJson(page, bench.gson.UserPage::class.java) },
        "jackson" to { Codecs.jackson.readValue(page, bench.jackson.UserPage::class.java) },
    )
    val trees = linkedMapOf<String, () -> Any?>(
        "kson `Json.parse` → `JsonValue`" to { KsonJson.parse(page) },
        "kotlinx `parseToJsonElement` → `JsonElement`" to { Codecs.kotlinx.parseToJsonElement(page) },
        "moshi `adapter(Any)` → `Map`/`List`" to { Codecs.moshiTree.fromJson(page) },
        "gson `JsonParser` → `JsonElement`" to { JsonParser.parseString(page) },
        "jackson `readTree` → `JsonNode`" to { Codecs.jackson.readTree(page) },
    )

    val report = buildString {
        appendLine("<!-- Generated by `./gradlew -p docs/benchmarks retained`; do not edit by hand. -->")
        appendLine()
        appendLine("Payload sizes as UTF-8: user ${"%,d".format(Payloads.user.toByteArray().size)} bytes, " +
            "20-user page ${"%,d".format(Payloads.page(20).toByteArray().size)} bytes, " +
            "1,000-user page ${"%,d".format(page.toByteArray().size)} bytes.")
        appendLine()
        appendLine("Input: 1,000-user page, ${"%,d".format(page.length)} chars (${"%,d".format(page.toByteArray().size)} bytes as UTF-8).")
        appendLine("The input `String` occupies ${kb(GraphLayout.parseInstance(page).totalSize())} on this heap.")
        appendLine()
        appendLine("```")
        appendLine(VM.current().details().trim())
        appendLine("```")
        appendLine()
        table("Typed result (`UserPage`)", typed)
        table("Untyped tree", trees)
        appendLine("### kson tree by class (20-user page)")
        appendLine()
        appendLine("```")
        appendLine(GraphLayout.parseInstance(KsonJson.parse(Payloads.page(20))).toFootprint().trim())
        appendLine("```")
    }
    File(out, "retained.md").writeText(report)
    println(report)
}

private fun StringBuilder.table(title: String, decoders: Map<String, () -> Any?>) {
    appendLine("### $title")
    appendLine()
    appendLine("| Library | Retained size | Objects |")
    appendLine("|---|---:|---:|")
    decoders.forEach { (name, decode) ->
        val layout = GraphLayout.parseInstance(decode())
        appendLine("| $name | ${kb(layout.totalSize())} | ${"%,d".format(layout.totalCount())} |")
    }
    appendLine()
}

private fun kb(bytes: Long) = "%,.0f KB".format(bytes / 1024.0)
