#!/usr/bin/env bash
# Compiles one small @Kson interface per case in the kson-probe module and records whether kson-ksp accepts it.
# Writes results/kson-type-probe.md. Run from anywhere: docs/benchmarks/scripts/kson-type-probe.sh
set -uo pipefail

bench_dir="$(cd "$(dirname "$0")/.." && pwd)"
gradlew="$bench_dir/../../gradlew"
src_dir="$bench_dir/kson-probe/src/main/kotlin/probe"
out="$bench_dir/results/kson-type-probe.md"
mkdir -p "$src_dir" "$bench_dir/results"
trap 'rm -rf "$bench_dir/kson-probe/src"' EXIT

{
  echo "<!-- Generated by scripts/kson-type-probe.sh; do not edit by hand. -->"
  echo
  echo "| Property or declaration | Result |"
  echo "|---|---|"
} > "$out"

# probe <title> <extra declarations> <@Kson interface body>
probe() {
  local title="$1" decls="$2" body="$3"
  cat > "$src_dir/Case.kt" <<EOF
package probe

import com.fajarnuha.kson.*

$decls

$body
EOF
  local log
  log="$("$gradlew" -p "$bench_dir" :kson-probe:compileKotlin --console=plain -q 2>&1)"
  if [[ $? -eq 0 ]]; then
    result="compiles"
  else
    result="rejected: \`$(grep -m1 -E '^e: ' <<<"$log" | sed -E 's#^e: (\[ksp\] )?[^ ]*Case.kt:[0-9]+(:[0-9]+)?: ##' | sed -E 's#file://[^ ]*Case.kt:[0-9:]+ ##' | cut -c1-160)\`"
  fi
  echo "| $title | $result |" | tee -a "$out"
}

probe "\`List<List<Int>>\`" "" "@Kson interface Case { val grid: List<List<Int>> }"
probe "\`List<String?>\`" "" "@Kson interface Case { val tags: List<String?> }"
probe "Backticked key \`\` \`first_name\` \`\`" "" "@Kson interface Case { val \`first_name\`: String }"
probe "Nested interface with a default getter" "" "@Kson interface Case { val inner: Inner get() = object : Inner { override val v = 1 }
  interface Inner { val v: Int } }"
probe "\`Map<String, Int>\`" "" "@Kson interface Case { val counts: Map<String, Int> }"
probe "\`Set<String>\`" "" "@Kson interface Case { val tags: Set<String> }"
probe "\`Array<String>\`" "" "@Kson interface Case { val tags: Array<String> }"
probe "\`Short\` / \`Byte\` / \`Char\`" "" "@Kson interface Case { val s: Short }"
probe "\`ULong\`" "" "@Kson interface Case { val id: ULong }"
probe "\`java.math.BigDecimal\`" "" "@Kson interface Case { val amount: java.math.BigDecimal }"
probe "\`java.time.Instant\`" "" "@Kson interface Case { val at: java.time.Instant }"
probe "Value class \`UserId\`" "@JvmInline value class UserId(val raw: Long)" "@Kson interface Case { val id: UserId }"
probe "Data class property" "data class Point(val x: Int)" "@Kson interface Case { val p: Point }"
probe "Recursive type (tree node)" "" "@Kson interface Case { val name: String; val children: List<Case> }"
probe "Generic interface" "" "@Kson interface Case<T> { val value: T }"
probe "\`var\` property" "" "@Kson interface Case { var name: String }"
probe "\`@Kson\` on a data class" "" "@Kson data class Case(val name: String)"
probe "Sealed interface hierarchy" "" "@Kson sealed interface Case { val type: String }
data class Circle(override val type: String, val r: Double) : Case"
